-- zett as a code editor: Doom Emacs' SPC tree, with Doom's keys wherever Doom has them.
-- Loaded after defaults.lua when zett runs in a terminal; init.lua can change any of it.

local z = zett
local function ui(name, desc, what, arg)
  z.command(name, function() z.ui(what, arg) end, { desc = desc })
end
local function map(keys, command, desc) z.map("n", keys, command, { desc = desc }) end

