-- zett's default keys: Emacs. Loaded when zett.opt.keys is "emacs" (the default); "vim" loads
-- editor.lua's Doom/Vim layer instead. Every key points at a command (M-x lists them all);
-- init.lua can rebind any of it: zett.map("e", "<C-x><C-b>", "switch-buffer").

local z = zett
local function map(keys, command, desc) z.map("e", keys, command, desc and { desc = desc } or nil) end

