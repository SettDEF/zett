-- ── Emacs's names for zett's commands, and the Emacs commands that ask first ──
-- An Emacs name runs zett's own command (C-h f says which); prompts are the minibuffer's.
local function alias(name, target)
  local desc
  for _, c in ipairs(z.commands()) do
    if c.name == target then desc = c.desc end
  end
  z.command(name, function() z.run(target) end, { desc = (desc or target) .. " (" .. target .. ")" })
end
local function ex(name, desc, line) z.command(name, function() z.ui("ex", line) end, { desc = desc }) end
local function ask(name, desc, spec) z.command(name, function() z.ui("prompt", spec) end, { desc = desc }) end
local function both(name, desc, ...)
  local steps = { ... }
  z.command(name, function()
    for _, s in ipairs(steps) do z.ui(s[1], s[2]) end
  end, { desc = desc })
end

