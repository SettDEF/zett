-- zett's default keys: Emacs. Loaded when zett.opt.keys is "emacs" (the default); "vim" loads
-- editor.lua's Doom/Vim layer instead. Every key points at a command (M-x lists them all);
-- init.lua can rebind any of it: zett.map("e", "<C-x><C-b>", "switch-buffer").

local z = zett
local function map(keys, command, desc) z.map("e", keys, command, desc and { desc = desc } or nil) end

-- ── moving ──
map("<C-f>", "forward-char")
map("<C-b>", "backward-char")
map("<C-n>", "next-line")
map("<C-p>", "previous-line")
map("<Right>", "forward-char")
map("<Left>", "backward-char")
map("<Down>", "next-line")
map("<Up>", "previous-line")
map("<C-a>", "beginning-of-line")
map("<C-e>", "end-of-line")
map("<M-m>", "back-to-indentation")
map("<M-f>", "forward-word")
map("<M-b>", "backward-word")
map("<M-lt>", "beginning-of-buffer")
map("<M-gt>", "end-of-buffer")
map("<M-}>", "forward-paragraph")
map("<M-{>", "backward-paragraph")

-- ── editing ──
map("<C-d>", "delete-char")
map("<BS>", "delete-backward-char")
map("<CR>", "newline")
map("<Tab>", "indent-for-tab-command")
map("<C-o>", "open-line")
map("<C-t>", "transpose-chars")
map("<C-k>", "kill-line")
map("<M-d>", "kill-word")
map("<M-BS>", "backward-kill-word")
map("<C-w>", "kill-region")
map("<M-w>", "copy-region-as-kill")
map("<C-y>", "yank")
map("<M-y>", "yank-pop")
map("<C-Space>", "set-mark-command")
map("<C-x><C-x>", "exchange-point-and-mark")
map("<C-x>h", "mark-whole-buffer")
map("<M-u>", "upcase-word")
map("<M-l>", "downcase-word")
map("<M-c>", "capitalize-word")
map("<M-\\>", "delete-horizontal-space")
map("<M-Space>", "just-one-space")
map("<C-/>", "undo")
map("<C-_>", "undo")
map("<C-x>u", "undo")
map("<C-g>", "keyboard-quit")
map("<M-;>", "comment")

-- ── files, buffers, windows (C-x) ──
z.group("<C-x>", "C-x: files, buffers, windows")
map("<C-x><C-f>", "find-file")
map("<C-x><C-r>", "recent-files")
map("<C-x><C-s>", "save-file")
map("<C-x><C-w>", "save-as")
map("<C-x>b", "switch-buffer")
map("<C-x><C-b>", "switch-buffer")
map("<C-x>k", "kill-buffer")
map("<C-x><Right>", "next-buffer")
map("<C-x><Left>", "previous-buffer")
map("<C-x>2", "split-below")
map("<C-x>3", "split-right")
map("<C-x>o", "window-next")
map("<C-x>0", "window-close")
map("<C-x>1", "window-only")
map("<C-x><C-c>", "quit")

-- ── commands, search, help ──
map("<M-x>", "execute-command")
map("<C-s>", "search-buffer")
map("<C-r>", "search-buffer")
map("<M-g><M-n>", "next-error")
map("<M-g><M-p>", "previous-error")
map("<M-.>", "goto-definition")
z.group("<C-h>", "C-h: help")
map("<C-h>d", "documentation-topics")
map("<C-h>f", "documentation")
map("<C-h>?", "help")
