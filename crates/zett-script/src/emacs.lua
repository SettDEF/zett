-- ── scroll-lock-mode (M-x; terminals rarely send Scroll Lock): the line keys scroll the text, the cursor stays where it is
-- on the screen (zett-edit screen.rs: scroll-lock-next-line / -previous-line) ──
local scroll_lock = false
z.command("scroll-lock-mode", function()
  scroll_lock = not scroll_lock
  local keys = { ["<C-n>"] = "next-line", ["<Down>"] = "next-line", ["<C-p>"] = "previous-line", ["<Up>"] = "previous-line" }
  for k, plain in pairs(keys) do
    local locked = plain == "next-line" and "scroll-lock-next-line" or "scroll-lock-previous-line"
    z.map("e", k, scroll_lock and locked or plain)
  end
  z.notify(scroll_lock and "Scroll-Lock mode enabled" or "Scroll-Lock mode disabled")
end, { desc = "The line keys scroll the text instead of moving the cursor (toggle)" })

