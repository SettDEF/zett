#!/usr/bin/env bash
# gen-options.sh: every Neovim option as a zett setting (crates/zett-tui/src/nvim_options.rs), from
# the installed Neovim itself: name, short name, type, default, the one-line description.
#   scripts/gen-options.sh      regenerate (needs nvim)
# zett's own table (settings.rs) wins for the names it has; these are the rest, accepted by :set,
# kept per buffer and shown in :help settings, marked there as doing nothing yet until they do.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
RT=$(nvim --clean --headless -c 'lua io.write(vim.env.VIMRUNTIME)' -c q 2>&1)
awk "/\*option-list\*/{f=1} f && /^'[a-z]/" "$RT/doc/quickref.txt" | sed "s/^'\([a-z]*\)'[ \t]*\('[a-z]*'\)\{0,1\}[ \t]*\(.*\)/\1\t\3/" > "$tmp/desc.tsv"
nvim --clean --headless -c "lua local o=vim.api.nvim_get_all_options_info(); local t={}; for n,i in pairs(o) do local d=i.default; if type(d)=='string' then d=d elseif type(d)=='boolean' then d=tostring(d) else d=tostring(d) end; t[#t+1]=n..'\31'..(i.shortname or '')..'\31'..i.type..'\31'..d:gsub('[\n\t\31]',' ') end; table.sort(t); vim.fn.writefile(t, '$tmp/opts.tsv')" -c q
out=crates/zett-tui/src/nvim_options.rs
{
    echo "//! Neovim's options, generated by scripts/gen-options.sh from $(nvim --version | head -1): every one"
    echo "//! :set accepts, with its type and default. zett's own table (settings.rs) wins for the names it has."
    echo
    echo "use crate::settings::{Kind, Setting};"
    echo
    echo "pub(crate) const NVIM: &[Setting] = &["
    while IFS=$'\037' read -r name short type def; do
        desc=$(awk -F'\t' -v n="$name" '$1==n{print $2; exit}' "$tmp/desc.tsv")
        kind=$(case "$type" in boolean) echo Bool;; number) echo Int;; *) echo Text;; esac)
        esc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
        sh=""
        if [ -n "$short" ]; then sh="\"$short\""; fi
        printf '    Setting { name: "%s", short: &[%s], kind: Kind::%s, default: "%s", about: "%s" },\n' "$name" "$sh" "$kind" "$(esc "$def")" "$(esc "$desc")"
    done < "$tmp/opts.tsv"
    echo "];"
} > "$out"
echo "$(grep -c 'Setting {' "$out") options → $out"
